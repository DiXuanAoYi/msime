"""Generate C++ constants from the single local TTS framing contract."""
import json
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1]
source = root / 'engine/contracts/tts_stream.json'
data = json.loads(source.read_text(encoding='utf-8'))
output = '// Generated by scripts/sync-tts-contract.py; do not edit.\n#pragma once\nnamespace TtsStreamContract\n{\n'
for key, value in data.items():
    if key == 'format':
        continue
    output += f'inline constexpr {"const char *" if isinstance(value, str) else "unsigned "}{key} = {json.dumps(value)};\n'
output += '} // namespace TtsStreamContract\n'
target = source.with_suffix('.h')
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8') == output, 'Run scripts/sync-tts-contract.py'
else:
    target.write_text(output, encoding='utf-8')
